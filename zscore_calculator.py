def _lms_zscore(measurement, L, M, S):
    """
    Fórmula LMS estándar de la OMS para calcular Z-score.
    Z = [(X/M)^L - 1] / (L * S)
    Si L ≈ 0: Z = ln(X/M) / S
    """
    if abs(L) < 1e-6:
        return math.log(measurement / M) / S
    return ((measurement / M) ** L - 1) / (L * S)


def _get_lms(tabla, key):
    """Obtiene LMS interpolando si la clave exacta no existe."""
    if key in tabla:
        return tabla[key]
    keys = sorted(tabla.keys())
    # Interpolación lineal entre los dos más cercanos
    lower = max([k for k in keys if k <= key], default=keys[0])
    upper = min([k for k in keys if k >= key], default=keys[-1])
    if lower == upper:
        return tabla[lower]
    t = (key - lower) / (upper - lower)
    L0, M0, S0 = tabla[lower]
    L1, M1, S1 = tabla[upper]
    return (
        L0 + t * (L1 - L0),
        M0 + t * (M1 - M0),
        S0 + t * (S1 - S0)
    )


def calcular_zscores(edad_meses, peso_kg, talla_cm, sexo='M'):
    """
    Calcula Z-scores antropométricos usando tablas LMS oficiales OMS 2006.
    Método idéntico al software WHO Anthro usado por el INEI en ENDES.

    Parámetros:
        edad_meses : int   — edad en meses completados (6-59)
        peso_kg    : float — peso en kg
        talla_cm   : float — talla en cm
        sexo       : str   — 'M' masculino, 'F' femenino

    Retorna:
        (z_talla_edad, z_peso_edad, z_peso_talla, z_imc)
    """
    edad = int(round(edad_meses))
    edad = max(0, min(60, edad))

    # Seleccionar tablas según sexo
    if sexo == 'M':
        tab_waz  = WAZ_BOYS
        tab_haz  = HAZ_BOYS
        tab_whz  = WHZ_BOYS
        tab_bmiz = BMIZ_BOYS
    else:
        tab_waz  = WAZ_GIRLS
        tab_haz  = HAZ_GIRLS
        tab_whz  = WHZ_GIRLS
        tab_bmiz = BMIZ_GIRLS

    # HAZ — Height-for-Age
    L, M, S = _get_lms(tab_haz, edad)
    z_haz = _lms_zscore(talla_cm, L, M, S)

    # WAZ — Weight-for-Age
    L, M, S = _get_lms(tab_waz, edad)
    z_waz = _lms_zscore(peso_kg, L, M, S)

    # WHZ — Weight-for-Height (interpolado por talla)
    talla_key = round(talla_cm / 5) * 5
    talla_key = max(45.0, min(120.0, float(talla_key)))
    L, M, S = _get_lms(tab_whz, talla_key)
    z_whz = _lms_zscore(peso_kg, L, M, S)

    # BMIZ — BMI-for-Age
    bmi = peso_kg / ((talla_cm / 100) ** 2)
    L, M, S = _get_lms(tab_bmiz, edad)
    z_bmi = _lms_zscore(bmi, L, M, S)

    # Limitar a rango [-6, 6] igual que WHO Anthro
    def clip(z):
        return round(max(-6.0, min(6.0, z)), 2)

    return clip(z_haz), clip(z_waz), clip(z_whz), clip(z_bmi)